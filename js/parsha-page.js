/* ══════════════════════════════════════════════════════
   IvritSuite — the parsha coloring pages: js/parsha-page.js
   The one script of every parsha/<slug>.html page (generated by scripts/build-parsha-pages.mjs from
   ParashaEmojis.md). Each page loads it deferred, after /js/i18n.js and /js/hebrew-calendar.js. It owns what the
   static page cannot say by itself:
   - the dark toggle (the suite's hebrewBlender_darkMode, the same OS-aware rule as every page's no-flash IIFE);
   - applyI18n: the static chrome (I18n.applyStaticI18n), the picture's alt text, the "read together with" line and
     the next-reading line in the UI's language;
   - the next Shabbat that reads this parasha (HebCal.nextOccurrence), on the Torah Trainer's own Diaspora/Israel
     choice when this device has one (hebrewTorahTrainer_settings.schedule, read and never written).
   The parasha comes from #ppMain's data attributes: data-n (1–54), data-en / data-he (the names, the Hebrew
   unpointed), and data-pair-en / data-pair-he (the parasha it is often read with, when it has one). It stores nothing
   of its own.
   ══════════════════════════════════════════════════════ */
'use strict';
(function () {
  function t(key, fallback, params) {
    if (window.I18n && I18n.has && I18n.has(key)) return I18n.t(key, params);
    return String(fallback).replace(/\{(\w+)\}/g, (m, k) => (params && k in params ? params[k] : m));
  }
  const lang = () => (window.I18n && I18n.lang) || document.documentElement.lang || 'en';
  const main = () => document.getElementById('ppMain');
  // A parasha's name in the UI's language (the Hebrew is unpointed): this page's (data-en / data-he) or its pair's
  // (which = 'pair': data-pair-en / data-pair-he).
  function nameOf(el, which) {
    const he = el.dataset[which ? which + 'He' : 'he'], en = el.dataset[which ? which + 'En' : 'en'];
    return lang() === 'he' && he ? he : en;
  }

  function israel() {
    try {
      const raw = localStorage.getItem('hebrewTorahTrainer_settings');
      const s = raw ? JSON.parse(raw, (k, v) => (k === '__proto__' || k === 'constructor' || k === 'prototype') ? undefined : v) : null;
      return !!(s && typeof s === 'object' && s.schedule === 'israel');
    } catch (e) { return false; }
  }

  // "Read this Shabbat, …" / "Next read on Shabbat, …", and the week's other parasha when it is doubled. V'Zot
  // HaBerachah is read on Simchat Torah, never on a Shabbat, so it says that instead.
  function renderNext() {
    const m = main(), box = document.getElementById('ppNext');
    if (!m || !box) return;
    const n = Number(m.dataset.n);
    if (n === 54) { box.textContent = t('parshapage.next.simchat_torah', 'Read on Simchat Torah, not on a Shabbat.'); return; }
    if (!window.HebCal || !HebCal.nextOccurrence) { box.textContent = ''; return; }
    let hit = null;
    try { hit = HebCal.nextOccurrence(n - 1, new Date(), { israel: israel() }); } catch (e) { hit = null; }
    if (!hit || !hit.date) { box.textContent = ''; return; }
    let date = '';
    try { date = new Intl.DateTimeFormat(lang(), { day: 'numeric', month: 'long', year: 'numeric' }).format(hit.date); }
    catch (e) { date = hit.date.toDateString(); }
    const soon = (hit.date.getTime() - Date.now()) < 7 * 864e5;
    let text = soon ? t('parshapage.next.this_week', 'Read this Shabbat, {date}.', { date })
                    : t('parshapage.next.later', 'Next read on Shabbat, {date}.', { date });
    if (Array.isArray(hit.idx) && hit.idx.length > 1 && m.dataset.pairEn)
      text += ' ' + t('parshapage.next.doubled', 'That week it is read together with {other}.', { other: nameOf(m, 'pair') });
    box.textContent = text;
  }

  function applyI18n() {
    if (!window.I18n) return;
    I18n.applyStaticI18n();
    const m = main();
    if (m) {
      const img = document.getElementById('ppImg');
      if (img) img.alt = t('parshapage.img_alt', 'Parshat {name} coloring page', { name: nameOf(m, '') }) + (lang() === 'he' ? '' : ': ' + img.dataset.altEn);
      const pair = document.getElementById('ppPair');
      if (pair && m.dataset.pairEn) {
        const combo = lang() === 'he' ? pair.dataset.comboHe : pair.dataset.comboEn;
        pair.textContent = t('parshapage.pair', 'Often read together with {other}, as {combo}.', { other: nameOf(m, 'pair'), combo });
      }
    }
    syncDarkLabel();
    renderNext();
  }

  function syncDarkLabel() {
    const b = document.getElementById('darkBtn');
    if (!b) return;
    const dark = document.body.classList.contains('dark');
    const lbl = b.querySelector('.hi-lbl');
    if (lbl) lbl.textContent = dark ? t('shared.darkmode.label_light', 'Light') : t('shared.darkmode.label_dark', 'Dark');
    b.setAttribute('aria-pressed', dark ? 'true' : 'false');
  }
  function toggleDark() {
    const dark = document.body.classList.toggle('dark');
    document.documentElement.classList.remove('dark-early');
    try { localStorage.setItem('hebrewBlender_darkMode', dark ? '1' : '0'); } catch (e) {}
    syncDarkLabel();
  }

  function init() {
    try {
      const s = localStorage.getItem('hebrewBlender_darkMode');
      if (s === '1' || (s === null && window.matchMedia && matchMedia('(prefers-color-scheme: dark)').matches)) document.body.classList.add('dark');
    } catch (e) {}
    const b = document.getElementById('darkBtn');
    if (b) b.addEventListener('click', toggleDark);
    syncDarkLabel();
    renderNext();   // English before the locale arrives; applyI18n re-says it in the UI's language
    if (window.I18n) { I18n.ready.then(applyI18n); I18n.onChange(applyI18n); }
  }
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', init);
  else init();
})();
