/* ══════════════════════════════════════════════════════
   IvritSuite — the holiday coloring pages: js/holiday-page.js
   The one script of every holidays/<slug>.html page (generated by scripts/build-holiday-pages.mjs from
   HolidayGuide.md). Each page loads it deferred, after /js/i18n.js and /js/hebrew-calendar.js. It owns what the
   static page cannot say by itself:
   - the dark toggle (the suite's hebrewBlender_darkMode, the same OS-aware rule as every page's no-flash IIFE);
   - applyI18n: the static chrome (I18n.applyStaticI18n), the picture's alt text and the countdown in the UI's
     language;
   - the countdown: how many days until the evening this holiday begins, or that it begins tonight or is under way
     (HebCal.holidayOccurrence — the Holiday Guide's own sentences, holidayguide.count.*), on the Torah Trainer's
     Diaspora/Israel choice when this device has one (hebrewTorahTrainer_settings.schedule, read and never written).
     Shabbat and Havdalah come every week and have no countdown (data-weekly).
   The holiday comes from #hpMain's data attributes: data-key (the calendar key), data-en / data-he (its names, the
   Hebrew pointed) and data-weekly. It stores nothing of its own.
   ══════════════════════════════════════════════════════ */
'use strict';
(function () {
  function t(key, fallback, params) {
    if (window.I18n && I18n.has && I18n.has(key)) return I18n.t(key, params);
    return String(fallback).replace(/\{(\w+)\}/g, (m, k) => (params && k in params ? params[k] : m));
  }
  const lang = () => (window.I18n && I18n.lang) || document.documentElement.lang || 'en';
  const main = () => document.getElementById('hpMain');
  const nameOf = (el) => (lang() === 'he' && el.dataset.he ? el.dataset.he : el.dataset.en);

  function israel() {
    try {
      const raw = localStorage.getItem('hebrewTorahTrainer_settings');
      const s = raw ? JSON.parse(raw, (k, v) => (k === '__proto__' || k === 'constructor' || k === 'prototype') ? undefined : v) : null;
      return !!(s && typeof s === 'object' && s.schedule === 'israel');
    } catch (e) { return false; }
  }
  function dateText(g) {
    const d = new Date(g.y, g.m - 1, g.d);
    try { return new Intl.DateTimeFormat(lang(), { weekday: 'long', day: 'numeric', month: 'long', year: 'numeric' }).format(d); }
    catch (e) { return d.toDateString(); }
  }

  // "Chanukah is in 17 days. It begins at sundown on Friday, December 4, 2026." — or tonight, or under way.
  function renderNext() {
    const m = main(), box = document.getElementById('hpNext');
    if (!m || !box) return;
    if (m.dataset.weekly === '1' || !window.HebCal || !HebCal.holidayOccurrence) { box.textContent = ''; return; }
    let o = null;
    try { o = HebCal.holidayOccurrence(m.dataset.key, new Date(), { israel: israel() }); } catch (e) { o = null; }
    if (!o) { box.textContent = ''; return; }
    const name = nameOf(m);
    let text, when = '';
    if (o.state === 'during') {
      text = o.days > 1 ? t('holidayguide.count.today_day', 'Today is day {day} of {days} of {name}', { name, day: o.day, days: o.days })
                        : t('holidayguide.count.today', 'Today is {name}', { name });
      if (o.days > 1 && o.day < o.days) when = t('holidayguide.count.ends', 'It ends at nightfall on {date}.', { date: dateText(o.endDate) });
    } else if (o.state === 'eve') {
      text = t('holidayguide.count.tonight', '{name} begins tonight', { name });
      when = t('holidayguide.count.first_day', 'Its first day is {date}.', { date: dateText(o.startDate) });
    } else {
      text = o.daysToEve === 1 ? t('holidayguide.count.days.one', '{name} is in {count} day', { name, count: 1 })
                               : t('holidayguide.count.days.other', '{name} is in {count} days', { name, count: o.daysToEve });
      when = t('holidayguide.count.begins', 'It begins at sundown on {date}.', { date: dateText(o.eveDate) });
    }
    box.textContent = text + '.' + (when ? ' ' + when : '');
  }

  function applyI18n() {
    if (!window.I18n) return;
    I18n.applyStaticI18n();
    const m = main(), img = document.getElementById('hpImg');
    if (m && img) img.alt = t('holidaypage.img_alt', '{name} coloring page', { name: nameOf(m) }) + (lang() === 'he' ? '' : ': ' + img.dataset.altEn);
    syncDarkLabel();
    renderNext();
  }

  function syncDarkLabel() {
    const b = document.getElementById('darkBtn');
    if (!b) return;
    const dark = document.body.classList.contains('dark');
    const lbl = b.querySelector('.hi-lbl');
    if (lbl) lbl.textContent = dark ? t('shared.darkmode.label_light', 'Light') : t('shared.darkmode.label_dark', 'Dark');
    b.setAttribute('aria-pressed', dark ? 'true' : 'false');
  }
  function toggleDark() {
    const dark = document.body.classList.toggle('dark');
    document.documentElement.classList.remove('dark-early');
    try { localStorage.setItem('hebrewBlender_darkMode', dark ? '1' : '0'); } catch (e) {}
    syncDarkLabel();
  }

  function init() {
    try {
      const s = localStorage.getItem('hebrewBlender_darkMode');
      if (s === '1' || (s === null && window.matchMedia && matchMedia('(prefers-color-scheme: dark)').matches)) document.body.classList.add('dark');
    } catch (e) {}
    const b = document.getElementById('darkBtn');
    if (b) b.addEventListener('click', toggleDark);
    syncDarkLabel();
    renderNext();   // English before the locale arrives; applyI18n re-says it in the UI's language
    if (window.I18n) { I18n.ready.then(applyI18n); I18n.onChange(applyI18n); }
  }
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', init);
  else init();
})();
