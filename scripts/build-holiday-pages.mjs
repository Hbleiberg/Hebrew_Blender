#!/usr/bin/env node
/**
 * build-holiday-pages.mjs — build the holiday coloring pages, holidays/<slug>.html, one per holiday that has its six
 * symbols, from HolidayGuide.md (read by scripts/holiday-catalog.mjs, the parser build-holiday-guide.mjs uses too).
 *
 * Each page is a static landing page for searches like "Chanukah coloring page": the holiday's coloring sheet as a
 * picture (holidays/img/<slug>-coloring-page.png, rendered from holiday_guide.html's own sheet builder at its
 * defaults), a Print button that opens that sheet in the Holiday Guide's builder ready to print
 * (holiday_guide.html?holiday=<slug>), when the holiday falls, its other spellings (**Also spelled:**), what it is,
 * and its six symbols — each drawing with its English and pointed Hebrew name and a sentence in both languages —
 * with the previous and next holiday's page. js/holiday-page.js adds the countdown and the UI-language chrome.
 *
 * The pages live in holidays/, with parsha/ and Stein_School/ a folder of pages outside the repo root: they fetch
 * nothing relatively (every path is absolute). Each carries the CSP, the gtag snippet with the cleaned
 * page_location, the no-flash IIFEs, the Google Fonts links, the palette and the header-icons and holiday-icons CSS
 * blocks copied from holiday_guide.html at build time (so the copies always match), and no account wiring.
 * holidays/index.html forwards a bare /holidays/ to the list on holiday_guide.html.
 *
 * PUBLISHED is the one switch between hidden and public. While it is false every page says noindex, sitemap.xml has
 * no "holiday coloring pages" block (one found there is removed), and holiday_guide.html must say noindex too (the
 * build fails otherwise). Set to true, the pages say index, the block lists holiday_guide.html and every page (an
 * existing <lastmod> is kept: update-sitemap.mjs owns the dates), and the hub must say index. The other steps of
 * being public (and of hiding it again) are docs/reference/holiday-guide.md → Publishing.
 *
 * holiday_guide.html's static list of these pages (#hgSheets) is hand-kept: the build fails while it does not name
 * exactly the holidays that have their symbols, in the catalog's order.
 *
 * The pictures are rendered with the preinstalled Playwright (its own python3 -m http.server on the repo root; Google
 * Fonts allowed so the sheet's letters are in their real faces) and reduced to 64 colours with Python's PIL when it
 * is installed. A picture is rendered when it is missing or when what its sheet shows changed: holidays/img/
 * inputs.json keeps a hash of each holiday's names and its symbols' names and drawings, plus RENDER_VERSION — bump
 * that when the sheet builder in holiday_guide.html (or js/coloring-art.js) changes how a sheet looks.
 *
 *   node scripts/build-holiday-pages.mjs              write the pages, the forwarder and the sitemap block; render stale pictures
 *   node scripts/build-holiday-pages.mjs --no-images  the same without rendering (a missing picture is reported)
 *   node scripts/build-holiday-pages.mjs --images=all re-render every picture
 *   node scripts/build-holiday-pages.mjs --check      write nothing; exit 1 if a page, the sitemap block or a picture is stale
 *
 * Run it after node scripts/build-holiday-guide.mjs whenever HolidayGuide.md changes. Never edit its outputs.
 */
