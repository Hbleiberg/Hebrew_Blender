// ── The sitemap block: the hub and every page while PUBLISHED, nothing at all while not ──────────────────────────
function sitemap(text) {
  const kept = new Map();
  const a = text.indexOf(SM_START), b = text.indexOf(SM_END);
  if ((a < 0) !== (b < 0) || b < a) die('sitemap.xml: the holiday coloring pages markers are unbalanced');
  if (a >= 0) for (const m of text.slice(a, b).matchAll(/<loc>([^<]+)<\/loc>\s*<lastmod>([^<]+)<\/lastmod>/g)) kept.set(m[1], m[2]);
  if (!PUBLISHED) return a < 0 ? text : text.slice(0, a) + text.slice(b + SM_END.length).replace(/^\n/, '');
  const today = new Date().toISOString().slice(0, 10);
  const entry = (loc, freq, pri) => `  <url>\n    <loc>${loc}</loc>\n    <lastmod>${kept.get(loc) || today}</lastmod>\n    <changefreq>${freq}</changefreq>\n    <priority>${pri}</priority>\n  </url>`;
  const block = [SM_START, entry(SITE + SOURCE_PAGE, 'weekly', '0.9'), ...pages.map((h) => entry(`${SITE}${DIR}/${h.slug}.html`, 'monthly', '0.6')), SM_END].join('\n');
  if (a >= 0) return text.slice(0, a) + block + text.slice(b + SM_END.length);
  const end = text.lastIndexOf('</urlset>');
  if (end < 0) die('sitemap.xml has no </urlset>');
  return text.slice(0, end) + block + '\n' + text.slice(end);
}

