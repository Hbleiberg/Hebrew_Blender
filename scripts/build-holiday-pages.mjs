async function render(list) {
  let chromium;
  try { const m = await import('/opt/node22/lib/node_modules/playwright/index.js'); chromium = (m.default || m).chromium; }
  catch (e) { try { const m = await import('playwright'); chromium = (m.default || m).chromium; } catch (e2) { die('Playwright is not available: run with --no-images, or where the headless recipe works (docs/reference/ops.md)'); } }
  const PORT = 8000 + Math.floor(Math.random() * 900);
  const server = spawn('python3', ['-m', 'http.server', String(PORT), '--bind', '127.0.0.1'], { cwd: ROOT, stdio: 'ignore' });
  await new Promise((r) => setTimeout(r, 900));
  const pil = spawnSync('python3', ['-I', '-c', 'import PIL'], { stdio: 'ignore' }).status === 0;
  if (!pil) console.warn('build-holiday-pages: Python PIL not found — the pictures are written unreduced (about three times larger).');
  const browser = await chromium.launch();
  try {
    // A fresh context: no stored options, so every sheet is drawn at the builder's defaults (six symbols, both labels,
    // nikkud, the title, the dividing line, to color in, Letter).
    const ctx = await browser.newContext({ viewport: { width: 1400, height: 1100 }, deviceScaleFactor: 2, serviceWorkers: 'block', colorScheme: 'light' });
    const pg = await ctx.newPage();
    const errors = [];
    pg.on('pageerror', (e) => errors.push(e.message));
    pg.on('console', (m) => { if (m.type() === 'warning' && m.text().startsWith('[coloring]')) errors.push(m.text()); });
    await pg.route('**/*', (r) => {
      const u = r.request().url();
      return (u.startsWith(`http://127.0.0.1:${PORT}/`) || /^(data|blob):/.test(u) || /^https:\/\/fonts\.(googleapis|gstatic)\.com\//.test(u)) ? r.continue() : r.abort();
    });
    mkdirSync(path.join(ROOT, IMG_DIR), { recursive: true });
    for (const h of list) {
      await pg.goto(`http://127.0.0.1:${PORT}/${SOURCE_PAGE}?holiday=${h.slug}&lang=en`, { waitUntil: 'load' });
      await pg.waitForSelector('#hgPages[data-ready="1"] .hg-sheet', { timeout: 15000 });
      await pg.evaluate(() => document.fonts.ready);
      await pg.waitForTimeout(500);   // the sheet's fit pass (hgFitAll) settles after the fonts
      const got = await pg.evaluate(() => ({ key: (document.querySelector('#hgPick input:checked') || {}).value,
        ticked: [...document.querySelectorAll('#hgSyms input:checked')].map((x) => Number(x.value)), sheets: document.querySelectorAll('#hgPages .hg-sheet').length }));
      if (got.key !== h.key || got.ticked.join() !== '0,1,2,3,4,5' || got.sheets !== 1) die(`${h.slug}: the builder opened on ${JSON.stringify(got)}, not ${h.key}'s six symbols on one sheet`);
      const out = path.join(ROOT, imgRel(h));
      const sheet = await pg.$('#hgPages .hg-sheet');
      await sheet.screenshot({ path: out });
      if (pil) {
        const q = spawnSync('python3', ['-I', '-c', 'import sys\nfrom PIL import Image\np=sys.argv[1]\nImage.open(p).convert("RGB").quantize(colors=64,method=Image.Quantize.FASTOCTREE,dither=Image.Dither.NONE).save(p,optimize=True)', out]);
        if (q.status !== 0) die(`${h.slug}: PIL could not reduce the picture: ${q.stderr}`);
      }
      recorded[h.slug] = want[h.slug];
      process.stdout.write('.');
    }
    if (errors.length) die(`${SOURCE_PAGE} threw while rendering: ${errors.join(' | ')}`);
    process.stdout.write('\n');
  } finally {
    await browser.close();
    server.kill();
  }
}

