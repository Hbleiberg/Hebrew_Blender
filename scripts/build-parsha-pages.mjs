// ── The sitemap block ────────────────────────────────────────────────────────────────────────────────────────────
function sitemap(text) {
  const kept = new Map();
  const a = text.indexOf(SM_START), b = text.indexOf(SM_END);
  if ((a < 0) !== (b < 0) || b < a) die('sitemap.xml: the parsha coloring pages markers are unbalanced');
  if (a >= 0) for (const m of text.slice(a, b).matchAll(/<loc>([^<]+)<\/loc>\s*<lastmod>([^<]+)<\/lastmod>/g)) kept.set(m[1], m[2]);
  const today = new Date().toISOString().slice(0, 10);
  const block = [SM_START, ...icons.map((ic) => {
    const loc = `${SITE}${DIR}/${slugOf(ic.en)}.html`;
    return `  <url>\n    <loc>${loc}</loc>\n    <lastmod>${kept.get(loc) || today}</lastmod>\n    <changefreq>monthly</changefreq>\n    <priority>0.6</priority>\n  </url>`;
  }), SM_END].join('\n');
  if (a >= 0) return text.slice(0, a) + block + text.slice(b + SM_END.length);
  const end = text.lastIndexOf('</urlset>');
  if (end < 0) die('sitemap.xml has no </urlset>');
  return text.slice(0, end) + block + '\n' + text.slice(end);
}

