async function render(list) {
  let chromium;
  try { const m = await import('/opt/node22/lib/node_modules/playwright/index.js'); chromium = (m.default || m).chromium; }
  catch (e) { try { const m = await import('playwright'); chromium = (m.default || m).chromium; } catch (e2) { die('Playwright is not available: run with --no-images, or where the headless recipe works (docs/reference/ops.md)'); } }
  const PORT = 8000 + Math.floor(Math.random() * 900);
  const server = spawn('python3', ['-m', 'http.server', String(PORT), '--bind', '127.0.0.1'], { cwd: ROOT, stdio: 'ignore' });
  await new Promise((r) => setTimeout(r, 900));
  const pil = spawnSync('python3', ['-I', '-c', 'import PIL'], { stdio: 'ignore' }).status === 0;
  if (!pil) console.warn('build-parsha-pages: Python PIL not found — the pictures are written unreduced (about three times larger).');
  const browser = await chromium.launch();
  try {
    const ctx = await browser.newContext({ viewport: { width: 1400, height: 1100 }, deviceScaleFactor: 4, serviceWorkers: 'block', colorScheme: 'light' });
    const pg = await ctx.newPage();
    const errors = [];
    pg.on('pageerror', (e) => errors.push(e.message));
    await pg.route('**/*', (r) => {
      const u = r.request().url();
      return (u.startsWith(`http://127.0.0.1:${PORT}/`) || /^(data|blob):/.test(u) || /^https:\/\/fonts\.(googleapis|gstatic)\.com\//.test(u)) ? r.continue() : r.abort();
    });
    mkdirSync(path.join(ROOT, IMG_DIR), { recursive: true });
    for (const ic of list) {
      const slug = slugOf(ic.en);
      await pg.goto(`http://127.0.0.1:${PORT}/${SOURCE_PAGE}?parsha=${slug}&lang=en`, { waitUntil: 'load' });
      await pg.waitForSelector('#etCsPages .et-cs-sheet', { timeout: 15000 });
      await pg.evaluate(() => document.fonts.ready);
      await pg.waitForTimeout(700);   // the sheet's fit pass (etCsFitAll) settles after the fonts
      const chosen = await pg.$$eval('#etCsChips input:checked', (a) => a.map((x) => Number(x.value)));
      if (chosen.length !== 1 || chosen[0] !== ic.n - 1) die(`${slug}: the popup opened on ${JSON.stringify(chosen)}, not parasha ${ic.n}`);
      const out = path.join(ROOT, imgRel(ic));
      const sheet = await pg.$('#etCsPages .et-cs-sheet');
      await sheet.screenshot({ path: out });
      if (pil) {
        const q = spawnSync('python3', ['-I', '-c', 'import sys\nfrom PIL import Image\np=sys.argv[1]\nImage.open(p).convert("RGB").quantize(colors=64,method=Image.Quantize.FASTOCTREE,dither=Image.Dither.NONE).save(p,optimize=True)', out]);
        if (q.status !== 0) die(`${slug}: PIL could not reduce the picture: ${q.stderr}`);
      }
      recorded[slug] = want[slug];
      process.stdout.write('.');
    }
    if (errors.length) die(`${SOURCE_PAGE} threw while rendering: ${errors.join(' | ')}`);
    process.stdout.write('\n');
  } finally {
    await browser.close();
    server.kill();
  }
}

