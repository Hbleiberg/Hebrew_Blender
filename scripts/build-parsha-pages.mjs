/**
 * build-parsha-pages.mjs — build the parsha coloring pages, parsha/<slug>.html, one per weekly Torah portion, from
 * ParashaEmojis.md (read by scripts/parasha-catalog.mjs, the parser build-parasha-icons.mjs uses too).
 *
 * Each page is a static, indexable landing page for searches like "Parshat Noach coloring page": the parasha's
 * coloring sheet as a picture (parsha/img/<slug>-coloring-page.png, rendered from parsha_emojis.html's own sheet
 * builder), a Print button that opens that sheet in the Parsha Emojis popup ready to print (parsha_emojis.html
 * ?parsha=<slug>: paper, outline or colored in, English or Hebrew text, pages per sheet), the Torah Trainer link,
 * the reading, the other spellings (**Also spelled:**), the summary, what the picture shows and why it was chosen
 * (English and Hebrew), the parasha it is often read with, and the previous and next parasha. js/parsha-page.js adds
 * the next Shabbat it is read and the UI-language chrome.
 *
 * The pages live in parsha/, the one folder of pages outside the repo root: they fetch nothing relatively (every path
 * is absolute) and no root-page tool lists them by accident. Each carries the CSP, the gtag snippet with the cleaned
 * page_location, the no-flash IIFEs, the Google Fonts links and the header-icons CSS block copied from
 * parsha_emojis.html at build time (so the copies always match), and no account wiring. parsha/index.html forwards a
 * bare /parsha/ to the list on parsha_emojis.html. sitemap.xml gets one <url> per page between the
 * "parsha coloring pages" markers (an existing <lastmod> is kept: update-sitemap.mjs owns the dates).
 *
 * The pictures are rendered with the preinstalled Playwright (the parasha-coloring-review.mjs recipe: its own
 * python3 -m http.server on the repo root; Google Fonts allowed so the sheet's titles are in their real faces) and
 * reduced to 64 colours with Python's PIL when it is installed (about 40 KB each instead of 120). A picture is
 * rendered when it is missing or when what its sheet shows changed: parsha/img/inputs.json keeps a hash of each
 * parasha's drawing, names, reading, summary and reason, plus RENDER_VERSION — bump that when the sheet builder in
 * parsha_emojis.html changes how a sheet looks. A new or changed picture needs a VERSION bump in sw.js (static media
 * is cache-first per version).
 *
 *   node scripts/build-parsha-pages.mjs              write the pages, the forwarder and the sitemap block; render stale pictures
 *   node scripts/build-parsha-pages.mjs --no-images  the same without rendering (a missing picture is reported)
 *   node scripts/build-parsha-pages.mjs --images=all re-render every picture
 *   node scripts/build-parsha-pages.mjs --check      write nothing; exit 1 if a page, the sitemap block or a picture is stale
 *
 * Run it after node scripts/build-parasha-icons.mjs whenever ParashaEmojis.md changes. Never edit its outputs.
 */
