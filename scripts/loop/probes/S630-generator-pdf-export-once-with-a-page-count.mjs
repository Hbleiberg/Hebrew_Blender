#!/usr/bin/env node
// S630 — the generator's Export PDF runs once and counts its pages on both of its buttons (pass F, long-build progress;
// the count is gate 2, approved). A 10-version class set takes 11–13 s (about a second a page, each capture one long
// task); the sticky footer's PDF button — the one in reach — said nothing all that time (only the sidebar's, off screen,
// read "⏳ Generating..."), stayed live, and a second press ran a second capture alongside and saved the PDF twice.
//
//   node scripts/loop/probes/S630-generator-pdf-export-once-with-a-page-count.mjs
//   EN light 1280 / HE dark 800 / EN dark 800 / HE light 1280, a fresh profile, a 6-version class set generated by a real
//   click. html2canvas and jsPDF (cdnjs, lazily loaded) are answered by stand-ins served at their URLs (a counted route
//   hit): the capture holds the main thread 300 ms like the real one, `save()` is counted. (1) The footer's PDF pressed by
//   a real click, again 150 ms later, then the sidebar's Export PDF: 1 save; while it runs both buttons are disabled and
//   every "Page k of 6" is painted on the footer's label (read in an animation frame, k = 1…6); afterwards both read their
//   own label again ("PDF" / "Export PDF" in the UI's language) with their icon, enabled. (2) The footer's PDF focused and
//   pressed by Enter, Enter again at once: 1 more save, the focus back on the footer's button. (3) While "Page 6 of 6"
//   shows, the footer bar and the sidebar overflow nothing and the button stays inside the sidebar. 0 page errors.
//   exit 1 when a step fails or a handle is missing. ROOT=<a git archive of the tree> runs another copy (the tree before
//   S630 fails every cell: two saves for the double press, the footer never counts).
import pkg from '/opt/node22/lib/node_modules/playwright/index.js';
import http from 'node:http';
import fs from 'node:fs';
import path from 'node:path';
const { chromium } = pkg;
const ROOT = path.resolve(process.env.ROOT || path.resolve(path.dirname(new URL(import.meta.url).pathname), '..', '..', '..'));
const TYPES = { '.html': 'text/html; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.json': 'application/json', '.webmanifest': 'application/manifest+json', '.svg': 'image/svg+xml', '.png': 'image/png', '.ttf': 'font/ttf', '.woff2': 'font/woff2', '.css': 'text/css' };
const server = http.createServer((req, res) => {
  const p = path.join(ROOT, decodeURIComponent(new URL(req.url, 'http://x').pathname));
  if (!p.startsWith(ROOT) || !fs.existsSync(p) || fs.statSync(p).isDirectory()) { res.writeHead(404); return res.end(); }
  res.writeHead(200, { 'content-type': TYPES[path.extname(p).toLowerCase()] || 'application/octet-stream' }); fs.createReadStream(p).pipe(res);
});
await new Promise(r => server.listen(0, '127.0.0.1', r));
const base = `http://127.0.0.1:${server.address().port}`;
let fail = 0;
const ok = (cond, msg) => { if (!cond) fail++; console.log(`${cond ? '✔' : '✘'} ${msg}`); };
const N = 6;
// The stand-ins: html2canvas busy-waits 300 ms and returns a canvas of the asked size; jsPDF answers every method it is
// asked for (a Proxy), knows its page size, and counts save().
const H2C = `window.html2canvas = async (el, o) => { await new Promise(r => setTimeout(r, 0)); const t = performance.now(); while (performance.now() - t < 300) {} const c = document.createElement('canvas'); c.width = Math.max(1, Math.round((o && o.width) || el.scrollWidth) * 2); c.height = Math.max(1, Math.round((o && o.height) || el.scrollHeight) * 2); return c; };`;
const JSPDF = `window.__saves = []; window.jspdf = { jsPDF: function (opts) { const land = opts && opts.orientation === 'landscape'; const w = land ? 279.4 : 215.9, h = land ? 215.9 : 279.4;
  const t = { internal: { pageSize: { getWidth: () => w, getHeight: () => h } }, save: name => { window.__saves.push(name); } };
  return new Proxy(t, { get: (o, k) => (k in o ? o[k] : () => p) }); var p; } };`;
const hits = { h2c: 0, pdf: 0 };
const browser = await chromium.launch();
for (const cell of [{ lang: 'en', dark: false, w: 1280 }, { lang: 'he', dark: true, w: 800 }, { lang: 'en', dark: true, w: 800 }, { lang: 'he', dark: false, w: 1280 }]) {
  const L = `${cell.lang} ${cell.dark ? 'dark' : 'light'} ${cell.w}`;
  const ctx = await browser.newContext({ viewport: { width: cell.w, height: 900 }, serviceWorkers: 'block', colorScheme: cell.dark ? 'dark' : 'light' });
  await ctx.route('**/*', r => { const u = r.request().url(); (u.startsWith(base) || u.startsWith('data:') || u.startsWith('blob:')) ? r.continue() : r.abort(); });
  await ctx.route(/cdnjs\.cloudflare\.com\/ajax\/libs\/(html2canvas|jspdf)\//, r => { const h = /html2canvas/.test(r.request().url()); hits[h ? 'h2c' : 'pdf']++; r.fulfill({ status: 200, contentType: 'text/javascript', body: h ? H2C : JSPDF }); });
  await ctx.addInitScript(([lang, dark]) => { if (sessionStorage.getItem('__s')) return; sessionStorage.setItem('__s', '1'); localStorage.setItem('hebrewBlender_lang', lang); localStorage.setItem('hebrewBlender_darkMode', dark ? '1' : '0'); }, [cell.lang, cell.dark]);
  const page = await ctx.newPage(); page.setDefaultTimeout(30000);
  const errors = []; page.on('pageerror', e => errors.push(String(e)));
  try {
    await page.goto(base + '/hebrew_blend_generator.html', { waitUntil: 'domcontentloaded' });
    await page.waitForFunction(() => window.I18n && typeof exportPDF === 'function'); await page.evaluate(() => window.I18n.ready);
    await page.fill('#classSetCount', String(N)); await page.dispatchEvent('#classSetCount', 'input');
    await page.locator('#generateBtn').scrollIntoViewIfNeeded(); await page.click('#generateBtn');
    await page.waitForFunction(n => { flushWorksheetBuild(); return document.querySelectorAll('#worksheet .sheet').length >= n; }, N);
    const FAB = '#genFabActions .btn[onclick="exportPDF()"]';
    await page.waitForSelector(FAB, { state: 'visible' });
    const want = await page.evaluate(n => ({ fab: I18n.t('worksheet.actions.pdf_mob'), side: I18n.t('worksheet.actions.export_pdf'), counts: Array.from({ length: n }, (_, k) => I18n.t('worksheet.actions.pdf_page_progress', { i: k + 1, n })) }), N);
    // The recorder: every animation frame, what the footer's and the sidebar's labels say and whether they are disabled.
    const arm = () => page.evaluate(([FAB, last]) => {
      const R = window.__r = { fab: [], disabledWhileBusy: true, layout: null, stop: false };
      const f = document.querySelector(FAB), s = document.getElementById('pdfBtn');
      (function tick() {
        const t = f.textContent.trim();
        if (!R.fab.includes(t)) R.fab.push(t);
        if (t.startsWith('⏳') && !(f.disabled && s.disabled)) R.disabledWhileBusy = false;
        if (t === last && !R.layout) {
          const bar = document.getElementById('genFab'), side = bar.closest('aside') || document.querySelector('.sidebar');
          const fb = f.getBoundingClientRect(), sb = side.getBoundingClientRect();
          R.layout = { barOver: bar.scrollWidth - bar.clientWidth, sideOver: side.scrollWidth - side.clientWidth, inside: fb.left >= sb.left - 1 && fb.right <= sb.right + 1, w: Math.round(fb.width) };
        }
        if (!R.stop) requestAnimationFrame(tick);
      })();
    }, [FAB, want.counts[N - 1]]);
    const settle = () => page.waitForFunction(FAB => { const f = document.querySelector(FAB); return !f.disabled && !f.textContent.includes('⏳') && !document.getElementById('pdfBtn').disabled; }, FAB, { timeout: 30000 });
    const after = () => page.evaluate(FAB => { window.__r.stop = true; const f = document.querySelector(FAB), s = document.getElementById('pdfBtn'); return { saves: window.__saves ? window.__saves.length : 0, r: window.__r, fab: f.textContent.trim(), side: s.textContent.trim(), icons: [f, s].every(b => { const i = b.querySelector('svg'); return i && getComputedStyle(i).display !== 'none'; }), enabled: !f.disabled && !s.disabled, focus: document.activeElement === f }; }, FAB);
    // (1) mouse: footer, footer again, the sidebar's
    await arm();
    // Raw mouse clicks at points taken before the export (a locator click waits out the busy page and lands after it
    // ends): the sidebar's button scrolled into view first, each point checked to hit its own button.
    await page.locator('#pdfBtn').scrollIntoViewIfNeeded();
    const pts = await page.evaluate(FAB => [document.querySelector(FAB), document.getElementById('pdfBtn')].map(b => { const r = b.getBoundingClientRect(), x = r.left + r.width / 2, y = r.top + r.height / 2, e = document.elementFromPoint(x, y); return { x, y, hit: !!e && b.contains(e) }; }), FAB);
    if (!pts.every(p => p.hit)) throw new Error('a PDF button is covered: ' + JSON.stringify(pts));
    await page.mouse.click(pts[0].x, pts[0].y); await page.waitForTimeout(150);
    await page.mouse.click(pts[0].x, pts[0].y); await page.waitForTimeout(150);
    await page.mouse.click(pts[1].x, pts[1].y);
    await page.waitForTimeout(200); await settle();
    const a = await after();
    const counted = want.counts.every(c => a.r.fab.includes(c));
    ok(a.saves === 1 && counted && a.r.disabledWhileBusy && a.fab === want.fab && a.side === want.side && a.icons && a.enabled,
      `${L} mouse: ${a.saves} save(s) for 3 presses; the footer painted ${a.r.fab.filter(t => t.startsWith('⏳')).length} busy labels, every "${want.counts[0]}"…"${want.counts[N - 1]}" ${counted}; disabled while busy ${a.r.disabledWhileBusy}; after «${a.fab}» / «${a.side}», icons ${a.icons}, enabled ${a.enabled}`);
    ok(!!a.r.layout && a.r.layout.barOver <= 0 && a.r.layout.sideOver <= 0 && a.r.layout.inside, `${L} layout at "${want.counts[N - 1]}": ${JSON.stringify(a.r.layout)}`);
    // (2) keyboard: Enter twice on the focused footer button
    await page.focus(FAB); await arm();
    await page.keyboard.press('Enter'); await page.keyboard.press('Enter');
    await page.waitForTimeout(200); await settle(); await page.waitForTimeout(100);
    const b = await after();
    ok(b.saves === 2 && b.focus && errors.length === 0 && hits.h2c > 0 && hits.pdf > 0,
      `${L} keyboard: ${b.saves - a.saves} more save(s) for Enter ×2, focus back on the footer's button ${b.focus}; stand-ins served ${hits.h2c}/${hits.pdf}; ${errors.length} errors`);
  } catch (e) { fail++; console.log(`✘ ${L}: ${String(e).split('\n')[0]}`); }
  await ctx.close();
}
await browser.close(); server.close();
console.log(fail ? `FAIL: ${fail}` : 'PASS: Export PDF runs once and counts its pages on both buttons');
process.exit(fail ? 1 : 0);
