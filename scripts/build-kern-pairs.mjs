#!/usr/bin/env node
/**
 * build-kern-pairs.mjs — build the Font Maker's list of the letter pairs that are most common in Hebrew words
 * (the "Common pairs" chips of its Kerning section).
 *
 * It reads data/hebrew_words.json (an object of arrays; each entry's `bare` is the word's letters without vowel
 * points), counts every pair of base letters that stand next to each other, and writes the most common ones into
 * Hebrew_Font_Maker.html between the two marker comments below, as
 *
 *     const KERN_COMMON_HE = [['05D5','05E8',567], …];     // [first, second, count], in reading order
 *
 * so the page never fetches the 3 MB word list. The rules:
 *   - A pair is two letters of U+05D0–U+05EA (final forms are letters of their own) in reading order — in Hebrew
 *     the first one sits on the right.
 *   - A mark (U+0591–U+05C7 except the maqaf, paseq, sof pasuq and nun hafukha: U+05BE, U+05C0, U+05C3, U+05C6)
 *     is skipped over: the letters either side of it are still a pair. Anything else — a maqaf, a space,
 *     punctuation, a letter of another script — breaks the pair, because two letters with something between
 *     them are never kerned against each other.
 *   - Each different spelling counts once, however many entries share it (the list has no word frequencies, and
 *     homographs would only count one spelling twice).
 *   - The list is the top KEEP pairs by count; equal counts are ordered by code point, so the output never depends
 *     on the order of the file.
 *
 *   node scripts/build-kern-pairs.mjs           rewrite the block in Hebrew_Font_Maker.html
 *   node scripts/build-kern-pairs.mjs --check   write nothing; exit 1 if the block differs from what the data builds
 *
 * Run it after any edit of data/hebrew_words.json, then bump VERSION in sw.js (the page is precached) and run
 * check-inline-js. Never edit the block by hand. No dependencies; paths come from this file's own location, so it
 * runs from any directory.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DATA = path.join(ROOT, 'data', 'hebrew_words.json');
const PAGE = path.join(ROOT, 'Hebrew_Font_Maker.html');
const KEEP = 60;
const START = '/* ── kern-pairs:start — GENERATED by scripts/build-kern-pairs.mjs from data/hebrew_words.json. Never edit by hand. ── */';
const END = '/* ── kern-pairs:end ── */';

const die = (msg) => { console.error('build-kern-pairs: ' + msg); process.exit(1); };

const args = process.argv.slice(2);
for (const a of args) if (a !== '--check') die(`unknown argument ${a} (use --check, or nothing)`);
const CHECK = args.includes('--check');

const isLetter = (c) => c >= 0x05D0 && c <= 0x05EA;
const isMark = (c) => c >= 0x0591 && c <= 0x05C7 && c !== 0x05BE && c !== 0x05C0 && c !== 0x05C3 && c !== 0x05C6;
const hex = (c) => c.toString(16).toUpperCase().padStart(4, '0');

function countPairs() {
  let raw;
  try { raw = fs.readFileSync(DATA, 'utf8'); } catch (e) { die('cannot read data/hebrew_words.json: ' + e.message); }
  let data;
  try { data = JSON.parse(raw); } catch (e) { die('data/hebrew_words.json is not valid JSON: ' + e.message); }
  if (!data || typeof data !== 'object' || Array.isArray(data)) die('data/hebrew_words.json: expected an object of arrays');
  const seen = new Set(), counts = new Map();
  for (const key of Object.keys(data)) {
    const list = data[key];
    if (!Array.isArray(list)) die(`data/hebrew_words.json: "${key}" is not an array`);
    for (const entry of list) {
      const bare = entry && entry.bare;
      if (typeof bare !== 'string' || !bare) die(`data/hebrew_words.json: an entry under "${key}" has no "bare" spelling`);
      if (seen.has(bare)) continue;
      seen.add(bare);
      let prev = 0;                                   // the last letter seen with nothing but marks since
      for (const ch of bare) {
        const c = ch.codePointAt(0);
        if (isMark(c)) continue;
        if (!isLetter(c)) { prev = 0; continue; }
        if (prev) { const k = hex(prev) + hex(c); counts.set(k, (counts.get(k) || 0) + 1); }
        prev = c;
      }
    }
  }
  if (counts.size < KEEP) die(`only ${counts.size} different pairs found — the word list looks wrong`);
  const ranked = [...counts].sort((a, b) => b[1] - a[1] || (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0)).slice(0, KEEP);
  return { ranked, spellings: seen.size, pairs: counts.size };
}

function buildBlock(ranked) {
  const cells = ranked.map(([k, n]) => `['${k.slice(0, 4)}','${k.slice(4)}',${n}]`);
  const lines = [];
  for (let i = 0; i < cells.length; i += 6) lines.push('  ' + cells.slice(i, i + 6).join(',') + (i + 6 < cells.length ? ',' : ''));
  return START + '\nconst KERN_COMMON_HE = [\n' + lines.join('\n') + '\n];\n' + END;
}

function splice(page, block) {
  const a = page.indexOf(START), b = page.indexOf(END);
  if (a < 0 || b < 0) die('Hebrew_Font_Maker.html: the kern-pairs markers are missing (start ' + (a < 0 ? 'missing' : 'found') + ', end ' + (b < 0 ? 'missing' : 'found') + ')');
  if (b < a) die('Hebrew_Font_Maker.html: the kern-pairs end marker comes before the start marker');
  if (page.indexOf(START, a + 1) >= 0 || page.indexOf(END, b + 1) >= 0) die('Hebrew_Font_Maker.html: a kern-pairs marker appears twice');
  return { now: page.slice(a, b + END.length), next: page.slice(0, a) + block + page.slice(b + END.length) };
}

const { ranked, spellings, pairs } = countPairs();
const block = buildBlock(ranked);
let page;
try { page = fs.readFileSync(PAGE, 'utf8'); } catch (e) { die('cannot read Hebrew_Font_Maker.html: ' + e.message); }
const { now, next } = splice(page, block);
const summary = `${KEEP} of ${pairs} pairs from ${spellings} spellings`;

if (CHECK) {
  if (now !== block) die('--check: the common-pairs block in Hebrew_Font_Maker.html is out of date with data/hebrew_words.json.\nRun node scripts/build-kern-pairs.mjs, then bump VERSION in sw.js.');
  console.log(`build-kern-pairs --check: up to date — ${summary}.`);
  process.exit(0);
}
if (now === block) { console.log(`build-kern-pairs: nothing to change — ${summary}.`); process.exit(0); }
fs.writeFileSync(PAGE, next);
console.log(`build-kern-pairs: wrote the block — ${summary}. Now bump VERSION in sw.js and run check-inline-js.`);
