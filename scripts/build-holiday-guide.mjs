#!/usr/bin/env node
/**
 * build-holiday-guide.mjs — build js/holiday-guide-data.js and the docs/holiday-guide/ previews from HolidayGuide.md.
 *
 * HolidayGuide.md (the repo root) is the catalog of the Holiday Guide: each holiday's names, other spellings, when
 * it falls, a brief description in English and Hebrew, its own symbol, and — once it has them — six symbols, each
 * with its English and pointed Hebrew name, a caption in both languages and its drawing (the inner markup of a 48×48
 * SVG on one line, in the parasha emojis' style). The catalog is the only hand-edited copy of all of it: fix it there
 * and re-run this script; never edit js/holiday-guide-data.js or a preview by hand. The catalog's format and rules
 * are scripts/holiday-catalog.mjs's header; a holiday whose symbol the shared holiday-icons block already draws
 * names that family instead of carrying a copy.
 *
 *   node scripts/build-holiday-guide.mjs                  check, then write the module + docs/holiday-guide/*.svg
 *   node scripts/build-holiday-guide.mjs --check          check only, and exit 1 if a file it writes would change
 *   node scripts/build-holiday-guide.mjs --catalog=<path> check a copy of the catalog only; write nothing
 *
 * After a change: node scripts/holiday-coloring-review.mjs (look at every row — the line art is derived from the
 * drawing by js/coloring-art.js, whose rules are not retuned for a holiday drawing), then
 * node scripts/build-holiday-pages.mjs (the holidays/ pages and their pictures).
 */
import { readFileSync, writeFileSync, existsSync, mkdirSync, readdirSync, unlinkSync } from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { ROOT, CATALOG, PREVIEW_DIR, readHolidayCatalog } from './holiday-catalog.mjs';

const OUT_JS = 'js/holiday-guide-data.js';
const CHECK = process.argv.includes('--check');
const CATALOG_ARG = process.argv.find((a) => a.startsWith('--catalog='));
const CATALOG_PATH = CATALOG_ARG ? path.resolve(CATALOG_ARG.slice('--catalog='.length)) : path.join(ROOT, CATALOG);

// The holiday-icons CSS block's palettes, built into each preview so it can be opened on its own.
const LIGHT = '--hol-line:#1a2744;--hol-gold:#c9922a;--hol-gold-lt:#f0d080;--hol-paper:#fffaf0;--hol-navy:#2a3b66;--hol-red:#c0392b;--hol-green:#3a7d44;--hol-blue:#3b6fb6;--hol-flame:#f0a030;--hol-ground:#fdf8ef';
const DARK = '--hol-line:#e8e0d0;--hol-gold:#e0a832;--hol-gold-lt:#f5d97a;--hol-paper:#e8e0d0;--hol-navy:#5a6d9c;--hol-red:#e0584a;--hol-green:#5aa865;--hol-blue:#6a9ae0;--hol-flame:#f6b84a;--hol-ground:#161c2a';

const { holidays, problems } = readHolidayCatalog(CATALOG_PATH);
const fail = (where, msg) => problems.push(`${where}: ${msg}`);
const stop = () => {
  if (!problems.length) return;
  console.error(`build-holiday-guide: ${problems.length} problem(s), nothing written:\n  ` + problems.join('\n  '));
  process.exit(1);
};
stop();

const data = holidays.map((h) => ({ key: h.key, slug: h.slug, en: h.en, he: h.he, weekly: h.weekly, spelled: h.spelled, alt: h.alt, icon: h.icon,
  when: h.when, about: h.about,
  symbols: h.symbols.map((s) => ({ en: s.en, he: s.he, alt: s.alt, svg: s.svg, caption: s.caption, meaning: s.meaning })) }));
const js = `/* ══════════════════════════════════════════════════════
   IvritSuite — the Holiday Guide's catalog: js/holiday-guide-data.js
   GENERATED by scripts/build-holiday-guide.mjs from HolidayGuide.md: edit a name, a description, a caption or a
   drawing there and re-run the script, never this file.
   Loaded by holiday_guide.html as a classic script placed before the page's inline <script>
   (window.HolidayGuide). It reads no settings, no I18n and no DOM.
   One entry per holiday, in the catalog's order (Shabbat and Havdalah, then the fifteen dated holidays in
   HebCal.HOLIDAY_KEYS order): { key, slug, en, he, weekly, spelled, alt, icon, when: { en, he },
   about: { en, he }, symbols: [ { en, he, alt, svg, caption: { en, he }, meaning: { en, he, svg } | null } ] } —
   key is the calendar key (HebCal.holidayOccurrence), slug the holidays/<slug>.html page, he and every symbol's he
   pointed Hebrew, icon / svg the inner markup of a flat 48×48 drawing in the holiday icons' style (every fill a
   --hol-* token of the holiday-icons CSS block, the outline from .hol-ico). symbols is empty until a holiday has
   its six. The text is plain (the build refuses markup, entities and ASCII quotes; a page still escapes it).
   HolidayGuide.list — the frozen entries; .get(keyOrSlug) — one, or null; .icon(keyOrSlug) and
   .symbol(keyOrSlug, i) — the drawing as '<span class="hol-ico" aria-hidden="true"><svg …>…</svg></span>', or ''.
   ══════════════════════════════════════════════════════ */
'use strict';
(function () {
  const LIST = [
${data.map((h) => `    /* ${h.en.replace(/\*\//g, '')} */ ${JSON.stringify(h)},`).join('\n')}
  ];
  const freeze = (o) => { if (o && typeof o === 'object') { Object.values(o).forEach(freeze); Object.freeze(o); } return o; };
  freeze(LIST);
  const wrap = (svg) => (svg ? '<span class="hol-ico" aria-hidden="true"><svg viewBox="0 0 48 48" focusable="false">' + svg + '</svg></span>' : '');
  function get(k) { return LIST.find((h) => h.key === k || h.slug === k) || null; }
  function icon(k) { const h = get(k); return wrap(h && h.icon); }
  function symbol(k, i) { const h = get(k), s = h && Number.isInteger(i) ? h.symbols[i] : null; return wrap(s && s.svg); }
  window.HolidayGuide = { list: LIST, get, icon, symbol, count: LIST.length };
})();
`;

// No browser gate parses js/: run the module here and read it back.
try {
  const box = { window: {} };
  vm.runInNewContext(js, box);
  const G = box.window.HolidayGuide;
  if (!G || G.count !== holidays.length || G.get('nothing') !== null || G.icon('nothing') !== '' || !G.icon(holidays[0].key)) fail(OUT_JS, 'does not load or answer as HolidayGuide');
  else if (JSON.stringify(G.list) !== JSON.stringify(data)) fail(OUT_JS, 'does not read back as written');
} catch (e) { fail(OUT_JS, `does not parse: ${e.message}`); }
stop();
if (CATALOG_ARG) {
  console.log(`build-holiday-guide --catalog: ${path.relative(process.cwd(), CATALOG_PATH)} is valid (${holidays.length} holidays); nothing written.`);
  process.exit(0);
}

const preview = (what, svg) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 48 48" width="48" height="48">
<!-- Preview of ${what} (HolidayGuide.md): the holiday-icons palette, light and dark. -->
<style>
svg{${LIGHT};stroke:var(--hol-line);stroke-width:2;stroke-linecap:round;stroke-linejoin:round;fill:none}
@media (prefers-color-scheme:dark){svg{${DARK}}}
</style>
${svg}
</svg>
`;
const previews = holidays.flatMap((h) => [
  [`${PREVIEW_DIR}/${h.slug}.svg`, preview(`the ${h.en.replace(/--/g, '-')} symbol`, h.icon)],
  ...h.symbols.map((s) => [`${PREVIEW_DIR}/${h.slug}-${s.n}.svg`, preview(`${h.en.replace(/--/g, '-')}: ${s.en.replace(/--/g, '-')}`, s.svg)]),
]);
const files = [[OUT_JS, js], ...previews];
const stale = files.filter(([rel, text]) => {
  const abs = path.join(ROOT, rel);
  return !existsSync(abs) || readFileSync(abs, 'utf8') !== text;
});
// A preview nothing in the catalog names any more (a holiday renamed, a symbol dropped).
const wanted = new Set(previews.map(([rel]) => path.basename(rel)));
const dir = path.join(ROOT, PREVIEW_DIR);
const orphans = existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith('.svg') && !wanted.has(f)) : [];
const symbolCount = holidays.reduce((n, h) => n + h.symbols.length, 0);
const complete = holidays.filter((h) => h.symbols.length).length;
const sum = `${holidays.length} holidays (${complete} with their symbols), ${symbolCount} symbol drawings`;
if (CHECK) {
  if (stale.length || orphans.length) {
    console.error(`build-holiday-guide --check: out of date with ${CATALOG}:\n  ` + [...stale.map(([rel]) => rel), ...orphans.map((f) => `${PREVIEW_DIR}/${f} (no longer in the catalog)`)].join('\n  ') +
      '\nRun node scripts/build-holiday-guide.mjs.');
    process.exit(1);
  }
  console.log(`build-holiday-guide --check: ${sum}, every file up to date.`);
} else {
  mkdirSync(dir, { recursive: true });
  for (const [rel, text] of stale) writeFileSync(path.join(ROOT, rel), text);
  for (const f of orphans) unlinkSync(path.join(dir, f));
  console.log(`build-holiday-guide: ${sum} checked; ${stale.length ? 'wrote ' + stale.length + ' file(s)' : 'every file already up to date'}${orphans.length ? ', removed ' + orphans.length + ' stale preview(s)' : ''}.`);
}
